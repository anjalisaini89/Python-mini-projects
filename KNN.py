# ============================================================
# KNN CLASSIFICATION - COMPLETE GOOGLE COLAB CODE
# ============================================================
# 1. Import Libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from google.colab import files
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    classification_report
)
# ============================================================
# 2. Upload Dataset
# ============================================================
uploaded = files.upload()
file_name = list(uploaded.keys())[0]
df = pd.read_csv(file_name)
print("Dataset Loaded Successfully!")
print("File Name:", file_name)
print("Dataset Shape:", df.shape)
# ============================================================
# 3. Display Dataset
# ============================================================
print("\nFirst 5 Rows:")
display(df.head())
print("\nColumn Names:")
print(df.columns.tolist())
# ============================================================
# 4. Check Missing Values
# ============================================================
print("\nMissing Values:")
print(df.isnull().sum())
# ============================================================
# 5. Create Target Variable
# ============================================================
# Median price
median_price = df["price"].median()
print("\nMedian Price:", median_price)
# 0 = Low Price
# 1 = High Price
df["price_category"] = np.where(
    df["price"] >= median_price,
    1,
    0
)
print("\nPrice Category:")
print(df["price_category"].value_counts())
# ============================================================
# 6. Select Features
# ============================================================
features = [
    "bedrooms",
    "bathrooms",
    "sqft_living",
    "sqft_lot",
    "floors",
    "waterfront",
    "view",
    "condition",
    "sqft_above",
    "sqft_basement",
    "yr_built",
    "yr_renovated",
    "price_per_sqft"
]
X = df[features]
y = df["price_category"]
print("\nFeatures Used:")
print(features)
# ============================================================
# 7. Train-Test Split
# ============================================================
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)
print("\nTraining Data:", X_train.shape)
print("Testing Data:", X_test.shape)
# ============================================================
# 8. Feature Scaling
# ============================================================
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)
# ============================================================
# 9. Create KNN Model
# ============================================================
# K = 5
knn = KNeighborsClassifier(n_neighbors=5)
# ============================================================
# 10. Train Model
# ============================================================
knn.fit(X_train_scaled, y_train)
print("\nKNN Model Trained Successfully!")
# ============================================================
# 11. Prediction
# ============================================================
y_pred = knn.predict(X_test_scaled)
print("\nFirst 20 Predictions:")
print(y_pred[:20])
# ============================================================
# 12. Actual vs Predicted
# ============================================================
results = pd.DataFrame({
    "Actual": y_test.values,
    "Predicted": y_pred
})
print("\nActual vs Predicted:")
display(results.head(20))
# ============================================================
# 13. Accuracy
# ============================================================
accuracy = accuracy_score(y_test, y_pred)
print("\n======================================")
print("          KNN RESULTS")
print("======================================")
print("\nK Value:", 5)
print(
    "Accuracy: {:.2f}%".format(
        accuracy * 100
    )
)
# ============================================================
# 14. Confusion Matrix
# ============================================================
cm = confusion_matrix(y_test, y_pred)
print("\nConfusion Matrix:")
print(cm)
# ============================================================
# 15. Classification Report
# ============================================================
print("\nClassification Report:")
print(
    classification_report(
        y_test,
        y_pred,
        target_names=[
            "Low Price",
            "High Price"
        ]
    )
)
# ============================================================
# 16. Plot Confusion Matrix
# ============================================================
plt.figure(figsize=(6, 4))
sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=[
        "Low Price",
        "High Price"
    ],
    yticklabels=[
        "Low Price",
        "High Price"
    ]
)
plt.title("KNN Confusion Matrix")
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.show()
# ============================================================
# 17. Test Different K Values
# ============================================================
k_values = range(1, 16)
accuracies = []
for k in k_values:
    model = KNeighborsClassifier(
        n_neighbors=k
    )
    model.fit(
        X_train_scaled,
        y_train
    )
    prediction = model.predict(
        X_test_scaled
    )
    acc = accuracy_score(
        y_test,
        prediction
    )
    accuracies.append(acc)
# ============================================================
# 18. Find Best K
# ============================================================
best_k = k_values[
    np.argmax(accuracies)
]
best_accuracy = max(accuracies)
print("\n======================================")
print("          BEST K VALUE")
print("======================================")
print("Best K:", best_k)
print(
    "Best Accuracy: {:.2f}%".format(
        best_accuracy * 100
    )
)
# ============================================================
# 19. Plot K vs Accuracy
# ============================================================
plt.figure(figsize=(8, 5))
plt.plot(
    k_values,
    accuracies,
    marker="o"
)
plt.xlabel("K Value")
plt.ylabel("Accuracy")
plt.title("KNN: K Value vs Accuracy")
plt.xticks(list(k_values))
plt.grid()
plt.show()
# ============================================================
# 20. Final Message
# ============================================================
print("\n======================================")
print("       KNN IMPLEMENTATION COMPLETE")
print("======================================")
print("Algorithm: K-Nearest Neighbors")
print("K Value Initially Used: 5")
print("Best K Value:", best_k)
print(
    "Best Accuracy: {:.2f}%".format(
        best_accuracy * 100
    )
)
